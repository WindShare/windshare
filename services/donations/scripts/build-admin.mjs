import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const SERVICE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const UI_ROOT = path.join(SERVICE_ROOT, 'admin-ui')
const OUTPUT_PATH = path.join(SERVICE_ROOT, 'src', 'admin', 'console-dist', 'assets.generated.ts')

async function bundleEntry(entryPath, loader) {
  const result = await build({
    entryPoints: [entryPath],
    bundle: true,
    write: false,
    minify: true,
    format: loader === 'ts' ? 'iife' : undefined,
    target: ['es2022', 'chrome120', 'safari17.5', 'firefox120'],
    charset: 'utf8',
    legalComments: 'none',
  })
  const output = result.outputFiles?.[0]
  if (!output) {
    throw new Error(`esbuild produced no output for ${entryPath}`)
  }
  return output.text
}

async function generateAssetsModule() {
  const [html, favicon, css, js] = await Promise.all([
    readFile(path.join(UI_ROOT, 'index.html'), 'utf8'),
    readFile(path.join(UI_ROOT, 'favicon.svg'), 'utf8'),
    bundleEntry(path.join(UI_ROOT, 'styles', 'main.css'), 'css'),
    bundleEntry(path.join(UI_ROOT, 'src', 'main.ts'), 'ts'),
  ])

  const normalizedHtml = html.replaceAll('\r\n', '\n')
  const normalizedFavicon = favicon.replaceAll('\r\n', '\n').trim()

  return [
    '// Generated by scripts/build-admin.mjs from admin-ui/. Do not edit directly.',
    `export const ADMIN_HTML = ${JSON.stringify(normalizedHtml)}`,
    `export const ADMIN_FAVICON_SVG = ${JSON.stringify(normalizedFavicon)}`,
    `export const ADMIN_APP_CSS = ${JSON.stringify(css)}`,
    `export const ADMIN_APP_JS = ${JSON.stringify(js)}`,
    '',
  ].join('\n')
}

async function main() {
  const checkOnly = process.argv.includes('--check')
  const generated = await generateAssetsModule()

  if (checkOnly) {
    let existing
    try {
      existing = await readFile(OUTPUT_PATH, 'utf8')
    } catch {
      existing = null
    }
    if (existing !== generated) {
      console.error('Generated admin assets are out of date. Run: pnpm -C services/donations build:admin')
      process.exitCode = 1
      return
    }
    console.log('admin console-dist: up to date')
    return
  }

  await mkdir(path.dirname(OUTPUT_PATH), { recursive: true })
  await writeFile(OUTPUT_PATH, generated, 'utf8')
  console.log(`admin console-dist: wrote ${path.relative(SERVICE_ROOT, OUTPUT_PATH)}`)
}

await main()
