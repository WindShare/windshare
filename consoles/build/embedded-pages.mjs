import { extname } from 'node:path'

const contentTypes = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
}

// The same public paths drive Vite development and Cargo's compile-time asset lookup.
export function embeddedPages(pages) {
  return {
    name: 'windshare-embedded-pages',
    configureServer(server) {
      server.middlewares.use((request, _response, next) => {
        const url = new URL(request.url, 'http://localhost')
        if (Object.hasOwn(pages, url.pathname)) request.url = '/' + pages[url.pathname] + url.search
        next()
      })
    },
    generateBundle: {
      order: 'post',
      handler(_, bundle) {
        const routes = []
        for (const file of Object.keys(bundle).sort()) {
          const kind = contentTypes[extname(file)]
          if (!kind) throw new Error('Unsupported console asset: ' + file)
          const paths = file.endsWith('.html')
            ? Object.keys(pages).filter(path => pages[path] === file)
            : ['/' + file]
          if (!paths.length) throw new Error('Missing public path for ' + file)
          const pattern = paths.map(path => JSON.stringify(path)).join(' | ')
          routes.push('    ' + pattern + ' => Some((include_str!(' + JSON.stringify(file) + '), ' + JSON.stringify(kind) + ')),')
        }
        this.emitFile({ type: 'asset', fileName: 'routes.rs', source: [
          '// Generated by consoles/build/embedded-pages.mjs.', 'match path {', ...routes, '    _ => None,', '}', '',
        ].join('\n') })
      },
    },
  }
}
