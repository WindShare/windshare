use gpui::{Svg, prelude::*, px, svg};

#[derive(Clone, Copy, Debug)]
pub enum Icon {
    Wind,
    Home,
    Folder,
    Download,
    Upload,
    Activity,
    Settings,
    Help,
    Plus,
    Arrow,
    ArrowLeft,
    ArrowUpRight,
    Chevron,
    ChevronDown,
    ChevronUp,
    Expand,
    Link,
    QrCode,
    Copy,
    Check,
    Close,
    Trash,
    More,
    Shield,
    User,
    Pencil,
    Mail,
    Globe,
    Search,
    Pause,
    Play,
    File,
    Image,
    Music,
    Monitor,
    Sun,
    Moon,
    Bell,
    Grid,
    List,
    Lock,
    Minimize,
    Maximize,
    Restore,
    Refresh,
    External,
    Sliders,
    Spark,
    Heart,
}

impl Icon {
    pub const fn name(self) -> &'static str {
        match self {
            Self::Wind => "wind",
            Self::Home => "home",
            Self::Folder => "folder",
            Self::Download => "download",
            Self::Upload => "upload",
            Self::Activity => "activity",
            Self::Settings => "settings",
            Self::Help => "help",
            Self::Plus => "plus",
            Self::Arrow => "arrow",
            Self::ArrowLeft => "arrow-left",
            Self::ArrowUpRight => "arrow-up-right",
            Self::Chevron => "chevron",
            Self::ChevronDown => "chevron-down",
            Self::ChevronUp => "chevron-up",
            Self::Expand => "expand",
            Self::Link => "link",
            Self::QrCode => "qr-code",
            Self::Copy => "copy",
            Self::Check => "check",
            Self::Close => "close",
            Self::Trash => "trash",
            Self::More => "more",
            Self::Shield => "shield",
            Self::User => "user",
            Self::Pencil => "pencil",
            Self::Mail => "mail",
            Self::Globe => "globe",
            Self::Search => "search",
            Self::Pause => "pause",
            Self::Play => "play",
            Self::File => "file",
            Self::Image => "image",
            Self::Music => "music",
            Self::Monitor => "monitor",
            Self::Sun => "sun",
            Self::Moon => "moon",
            Self::Bell => "bell",
            Self::Grid => "grid",
            Self::List => "list",
            Self::Lock => "lock",
            Self::Minimize => "minimize",
            Self::Maximize => "maximize",
            Self::Restore => "restore",
            Self::Refresh => "refresh",
            Self::External => "external",
            Self::Sliders => "sliders",
            Self::Spark => "spark",
            Self::Heart => "heart",
        }
    }
}

pub fn icon(name: Icon, size: f32) -> Svg {
    svg()
        .path(format!("icons/{}", name.name()))
        .size(px(size))
        .flex_shrink_0()
}
