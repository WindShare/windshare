use super::Language;

// One declaration defines the key and every translation, so missing entries fail to compile.
macro_rules! messages {
    ($($key:ident => ($english:literal, $chinese:literal)),* $(,)?) => {
        #[derive(Clone, Copy, Debug)]
        pub enum Text { $($key),* }

        impl Language {
            pub const fn text(self, message: Text) -> &'static str {
                match (self, message) {
                    $((Self::English, Text::$key) => $english,
                      (Self::SimplifiedChinese, Text::$key) => $chinese),*
                }
            }
        }
    };
}

